"""Materialise the guidance skill into the skills tree at install time.

The repository ships **zero** `SKILL.md` files on purpose: a bundled skill sits in
context and fires before the operator decided they wanted it. So the guidance lives
here as `templates/smartclaude-guide.md` and is copied into
`<skills_root>/smartclaude-guide/SKILL.md` only when someone installs.

The same restraint as `instructions.py` applies to the destination: if a file is
already there and it is not one we wrote, we stop. A hand-written skill outranks a
generated one, and silently replacing it would delete work.

A generated file is recognisable by its marker line, which also carries the version
so an install can tell "already current" from "older, refresh me".
"""

from __future__ import annotations

import os
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

SKILL_NAME = "smartclaude-guide"
MARKER = "<!-- Generated by smartclaude install."
REPO_ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = REPO_ROOT / "templates" / f"{SKILL_NAME}.md"


@dataclass
class Result:
    action: str          # created | updated | unchanged | foreign | missing-template | error
    path: Path
    detail: str = ""

    def describe(self) -> str:
        if self.action == "created":
            return f"{self.path}: guidance skill installed"
        if self.action == "updated":
            return f"{self.path}: guidance skill refreshed"
        if self.action == "unchanged":
            return f"{self.path}: guidance skill already current"
        if self.action == "removed":
            return f"{self.path}: guidance skill removed"
        if self.action == "foreign":
            return (
                f"{self.path}: exists and was not written by smartclaude; left alone. "
                f"Move it aside if you want the generated one"
            )
        return f"{self.path}: {self.detail or self.action}"


def _skills_root() -> Path:
    root = os.environ.get("CLAUDE_CONFIG_DIR") or os.path.expanduser("~/.claude")
    return Path(root).expanduser() / "skills"


def target(root: Path | None = None) -> Path:
    return (root or _skills_root()) / SKILL_NAME / "SKILL.md"


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".skill.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except Exception:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def install(root: Path | None = None, template: Path | None = None) -> Result:
    dest = target(root)
    src = template or TEMPLATE

    if not src.is_file():
        return Result("error", dest, f"template not found: {src}")

    desired = src.read_text(encoding="utf-8")

    if not dest.exists():
        _atomic_write(dest, desired)
        return Result("created", dest)

    current = dest.read_text(encoding="utf-8")
    if MARKER not in current:
        return Result("foreign", dest)

    if current == desired:
        return Result("unchanged", dest)

    _atomic_write(dest, desired)
    return Result("updated", dest)


def remove(root: Path | None = None) -> Result:
    """Remove the generated skill, and its folder when nothing else is in it."""
    dest = target(root)
    if not dest.exists():
        return Result("absent", dest, "guidance skill is not installed")
    current = dest.read_text(encoding="utf-8")
    if MARKER not in current:
        return Result("foreign", dest)
    dest.unlink()
    folder = dest.parent
    try:
        if folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
    except OSError:
        pass
    return Result("removed", dest)


def status(root: Path | None = None) -> Result:
    dest = target(root)
    if not dest.exists():
        return Result("unchanged", dest, "not installed")
    current = dest.read_text(encoding="utf-8")
    if MARKER not in current:
        return Result("foreign", dest)
    return Result("unchanged", dest, "installed")


def _main(argv: list[str]) -> int:
    import argparse, json

    ap = argparse.ArgumentParser(description="Install the smartclaude guidance skill")
    ap.add_argument("action", choices=["install", "remove", "status"])
    ap.add_argument("--skills-root", help="override the skills directory")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)

    root = Path(args.skills_root).expanduser() if args.skills_root else None
    fn = {"install": install, "remove": remove, "status": status}[args.action]
    result = fn(root)

    if args.json:
        print(json.dumps({"action": result.action, "path": str(result.path), "detail": result.detail}))
    else:
        print(result.describe())
    return 1 if result.action in ("error", "foreign") else 0


if __name__ == "__main__":
    raise SystemExit(_main(sys.argv[1:]))
